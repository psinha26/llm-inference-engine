#!/usr/bin/env python3
"""Generate src/tokenizer/unicode_tables.h: codepoint ranges for \\p{L} (letters) and \\p{N} (numbers).

The GPT-2 pre-tokenizer regex needs Unicode general categories. Rather than pull in ICU, this
script bakes the ranges into a header once, using Python's unicodedata. Re-run only to update
the Unicode version:  python3 scripts/gen_unicode_tables.py > src/tokenizer/unicode_tables.h
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"inline constexpr CodepointRange {name}[] = {{")
    for i in range(0, len(rs), 4):
        print("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 4]))
    print("};")


cat = unicodedata.category
letters = ranges(lambda cp: cat(chr(cp)).startswith("L"))
numbers = ranges(lambda cp: cat(chr(cp)).startswith("N"))

print(f"// Generated by scripts/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}. Do not edit.")
print("#pragma once\n#include <cstdint>\n\nnamespace unicode_tables {\n")
print("struct CodepointRange { uint32_t lo, hi; };\n")
emit("kLetters", letters)
print()
emit("kNumbers", numbers)
print("\n}  // namespace unicode_tables")
print(f"generated {len(letters)} letter ranges, {len(numbers)} number ranges", file=sys.stderr)
